"""Human-reviewed proposal generation from GPC metrics and drift signals."""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from pathlib import Path
import re
from typing import Any, Callable, Iterable

from gpc.drift import list_drift_signals
from gpc.graph_query import graph_summary
from gpc.self_metrics import list_snapshots


@dataclass(frozen=True)
class ProposalResult:
    path: Path
    project_slug: str
    signal_count: int
    snapshot_count: int
    proposal_slug: str


def generate_proposal(
    *,
    project_slug: str,
    output_dir: str | Path = "docs/proposals",
    generated_on: date | None = None,
    overwrite: bool = False,
    signals_loader: Callable[..., list[dict[str, Any]]] = list_drift_signals,
    snapshots_loader: Callable[..., list[dict[str, Any]]] = list_snapshots,
    graph_summary_loader: Callable[..., dict[str, Any]] = graph_summary,
) -> ProposalResult:
    """Render one reviewable proposal without changing source code or opening a PR."""

    signals = sorted(
        signals_loader(project_slug=project_slug, unresolved_only=True, limit=50),
        key=lambda signal: _severity_order(str(signal.get("severity", "info"))),
    )
    snapshots = snapshots_loader(project_slug=project_slug, limit=10)
    summary = graph_summary_loader(project_slug, top_k_gods=5)
    proposal_slug = _proposal_slug(signals)
    day = generated_on or date.today()
    destination = (
        Path(output_dir) / f"{day.isoformat()}-{project_slug}-{proposal_slug}.md"
    )

    if destination.exists() and not overwrite:
        raise FileExistsError(
            f"Proposal already exists: {destination}. Pass overwrite=True to replace it."
        )

    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        _render_proposal(
            project_slug=project_slug,
            signals=signals,
            snapshots=snapshots,
            graph_summary=summary,
            generated_on=day,
        ),
        encoding="utf-8",
    )
    return ProposalResult(
        path=destination,
        project_slug=project_slug,
        signal_count=len(signals),
        snapshot_count=len(snapshots),
        proposal_slug=proposal_slug,
    )


def _render_proposal(
    *,
    project_slug: str,
    signals: Iterable[dict[str, Any]],
    snapshots: Iterable[dict[str, Any]],
    graph_summary: dict[str, Any],
    generated_on: date,
) -> str:
    signal_rows = list(signals)
    snapshot_rows = list(snapshots)
    lines = [
        f"# Proposal: {project_slug} auto-research — {generated_on.isoformat()}",
        "",
        "> Generated by `scripts/auto_research.py`. This is an advisory document:",
        "> it never edits source code, creates a pull request, or merges changes.",
        "",
        "## Observed signal",
        "",
    ]

    if signal_rows:
        for signal in signal_rows:
            lines.extend(
                [
                    f"- **{signal.get('severity', 'info').upper()}** "
                    f"`{signal.get('signal_type', 'unknown')}`: "
                    f"{signal.get('message', 'No message supplied.')}",
                    f"  - Evidence: `{signal.get('evidence') or {}}`",
                ]
            )
    else:
        lines.extend(
            [
                "- **INFO** `metrics_baseline_incomplete`: no unresolved drift signal "
                "is available yet.",
                "- Evidence: the current metrics history is shown below; longitudinal "
                "comparison needs additional scheduled snapshots.",
            ]
        )

    lines.extend(["", "## Metrics evidence", ""])
    if snapshot_rows:
        lines.extend(
            [
                "| Captured at | Source | Graphify nodes | Communities | Weakly connected |",
                "|---|---|---:|---:|---:|",
            ]
        )
        for snapshot in snapshot_rows:
            lines.append(
                "| {created_at} | {source} | {nodes} | {communities} | {weakly} |".format(
                    created_at=snapshot.get("created_at", "unknown"),
                    source=snapshot.get("source", "unknown"),
                    nodes=snapshot.get("graphify_nodes", "n/a"),
                    communities=snapshot.get("community_count", "n/a"),
                    weakly=snapshot.get("weakly_connected_nodes", "n/a"),
                )
            )
    else:
        lines.append("No self-metrics snapshots are available for this project.")

    lines.extend(["", "## Graph context", ""])
    if graph_summary.get("found"):
        god_nodes = graph_summary.get("god_nodes") or []
        communities = graph_summary.get("communities") or []
        lines.append(
            f"Graphify projection is available with {len(god_nodes)} reported god node(s) "
            f"and {len(communities)} reported community record(s)."
        )
        if god_nodes:
            labels = [str(node.get("label", "unknown")) for node in god_nodes[:5]]
            lines.append(
                f"Topological focus for review: {', '.join(f'`{label}`' for label in labels)}."
            )
    else:
        lines.append("No Graphify projection is currently available for this project.")

    lines.extend(
        [
            "",
            "## Causal hypothesis",
            "",
            (
                "The observed drift may reflect a meaningful topology or extraction change."
                if signal_rows
                else "The project has insufficient longitudinal evidence to distinguish "
                "normal graph variation from drift."
            ),
            "",
            "## Suggested human-reviewed change",
            "",
            (
                "Inspect the affected nodes and evidence, then decide whether the related "
                "code, documentation, or indexing rules need a targeted change."
                if signal_rows
                else "Keep the scheduled metrics collector enabled and revisit this proposal "
                "after sufficient snapshots have accumulated (the roadmap requires two weeks)."
            ),
            "",
            "## Risk and rollback",
            "",
            "This document changes no runtime behavior. Discarding the proposal or deleting "
            "this file fully reverts the auto-research output.",
            "",
        ]
    )
    return "\n".join(lines)


def _proposal_slug(signals: list[dict[str, Any]]) -> str:
    candidate = (
        str(signals[0].get("signal_type", "")) if signals else "metrics-baseline"
    )
    normalized = re.sub(r"[^a-z0-9]+", "-", candidate.lower()).strip("-")
    return normalized or "metrics-baseline"


def _severity_order(severity: str) -> int:
    return {"critical": 0, "warning": 1, "info": 2}.get(severity.lower(), 3)
